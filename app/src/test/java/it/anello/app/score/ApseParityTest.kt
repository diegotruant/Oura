    @Test fun matchesPython() {
        val start = LocalDate.of(2026, 1, 1)
        val history = rows.map { r ->
            DailySummary(
                date = start.plusDays(r.day.toLong()),
                sleepStartMs = if (r.sleepMin > 0) 1L else null,
                asleepMin = r.sleepMin,
                avgHrv = r.rmssd,
            )
        }
        val out = Apse.replay(history, 8.0, setOf(start.plusDays(120)))
        for (r in rows) {
            val d = out.getValue(start.plusDays(r.day.toLong()))
            assertEquals("stato giorno ${r.day}", r.status, d.status)
            if (r.recovery == null) assertNull("recupero giorno ${r.day}", d.recovery)
            else assertEquals("recupero giorno ${r.day}", r.recovery, d.recovery!!, 1e-9)
        }
    }
